import { defineField, defineType } from "sanity";
import { seoField } from "./seoFields";

export const magazineEdition = defineType({
  name: "magazineEdition",
  title: "Magazine Edition",
  type: "document",
  fieldsets: [
    { name: "webLive", title: "Web View: the cover story as a web page", options: { collapsible: true, collapsed: false } },
  ],
  fields: [
    defineField({
      name: "editionLabel",
      title: "Edition label",
      type: "string",
      description: 'Short label shown above the title. e.g. "Edition 014 · October 2026"',
      validation: (r) => r.required(),
    }),
    defineField({
      name: "featuredPersonName",
      title: "Featured person",
      type: "string",
      validation: (r) => r.required(),
    }),
    defineField({
      name: "title",
      title: "Headline",
      type: "string",
      description: "The long editorial headline that appears below the person's name.",
      validation: (r) => r.required(),
    }),
    defineField({
      name: "subtitle",
      title: "Subtitle",
      type: "text",
      rows: 2,
      description: "One-line summary. Shown on the edition's card in the archive, and next to the cover when Description is empty.",
    }),
    defineField({
      name: "slug",
      title: "URL slug",
      type: "slug",
      options: { source: "title", maxLength: 96 },
      validation: (r) => r.required(),
    }),
    defineField({
      name: "cover",
      title: "Cover image",
      type: "image",
      options: { hotspot: true },
      fields: [
        defineField({ name: "alt", title: "Alt text", type: "string" }),
      ],
      validation: (r) => r.required(),
    }),
    defineField({
      name: "description",
      title: "Description",
      type: "text",
      rows: 5,
      description: "A few lines about this edition, shown next to the cover on the edition page. Put **two stars** around words to make them bold.",
    }),
    defineField({
      name: "storyTitle",
      title: "Story title",
      type: "string",
      fieldset: "webLive",
      description: "The title at the top of the Web View page. Leave empty to use the Headline.",
    }),
    defineField({
      name: "storyIntro",
      title: "Short intro",
      type: "text",
      rows: 3,
      fieldset: "webLive",
      description: "A few lines shown in italics under the story title, next to the cover.",
    }),
    defineField({
      name: "storyBanner",
      title: "Banner image (optional)",
      type: "image",
      fieldset: "webLive",
      options: { hotspot: true },
      fields: [defineField({ name: "alt", title: "Alt text", type: "string" })],
      description: "A wide picture between the top of the page and the story. The cover is always shown, so this can stay empty.",
    }),
    defineField({
      name: "storyBody",
      title: "Story",
      type: "array",
      of: [{ type: "text", rows: 5 }],
      fieldset: "webLive",
      description: "Each box is one paragraph. Put **two stars** around words to make them bold. Start a box with ## to make it a small heading. The Web View button appears once this has text.",
    }),
    defineField({
      name: "pullQuote",
      title: "Pull quote (not shown)",
      type: "text",
      rows: 3,
      description: "No longer shown on the site. The archive search still looks in it.",
      hidden: ({ value }) => !value,
    }),
    defineField({
      name: "pullQuoteAttribution",
      title: "Pull-quote attribution (not shown)",
      type: "string",
      hidden: ({ value }) => !value,
    }),
    defineField({
      name: "roleTags",
      title: "Role tags",
      type: "array",
      of: [{ type: "string" }],
      description: "The first tag is shown under the name in the home page Cover stories.",
      options: { layout: "tags" },
    }),
    defineField({
      name: "pdfFile",
      title: "PDF file (Digital Live)",
      type: "file",
      options: { accept: "application/pdf" },
    }),
    defineField({
      name: "publishedOn",
      title: "Published on (display)",
      type: "string",
      description: 'Free-form display string. e.g. "October 2026"',
    }),
    defineField({
      name: "publishedYear",
      title: "Published year (for filtering)",
      type: "number",
      description: "Numeric year used by the archive filter.",
      validation: (r) => r.required().integer().min(2000).max(2100),
    }),
    defineField({
      name: "body",
      title: "Old paragraphs (not shown)",
      type: "array",
      of: [{ type: "text", rows: 4 }],
      description: "No longer shown on the site.",
      hidden: ({ value }) => !value || value.length === 0,
    }),
    defineField({
      name: "order",
      title: "Display order",
      type: "number",
      description: "Lower number = appears first in the archive.",
      initialValue: 100,
    }),
    seoField,
  ],
  orderings: [
    {
      title: "Newest first",
      name: "publishedDesc",
      by: [{ field: "publishedYear", direction: "desc" }, { field: "order", direction: "asc" }],
    },
  ],
  preview: {
    select: {
      title: "featuredPersonName",
      subtitle: "editionLabel",
      media: "cover",
    },
  },
});
